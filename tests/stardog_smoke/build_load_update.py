"""Build load-all.rq: one SPARQL Update that loads the smoke test into a Stardog database.

  ontology + IDMP-O extract -> tag:stardog:api:context:schema  (the graph Stardog reasons over)
  toy data                  -> default graph
  SHACL shapes              -> https://dgg32.github.io/glp/graph/smoke-shapes

Paste the generated file into Stardog Studio and run it; no file upload needed.

Usage: .venv/bin/python tests/stardog_smoke/build_load_update.py
"""
from pathlib import Path

from rdflib import Graph

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SCHEMA_GRAPH = "tag:stardog:api:context:schema"
SHAPES_GRAPH = "https://dgg32.github.io/glp/graph/smoke-shapes"


def ntriples(*paths):
    g = Graph()
    for p in paths:
        g.parse(p)
    return g.serialize(format="nt").strip(), len(g)


def main():
    schema, n_schema = ntriples(ROOT / "ontology" / "diabetes-market.ttl",
                                ROOT / "ontology" / "imports" / "idmp-o-1.4.0-extract.ttl")
    data, n_data = ntriples(HERE / "toy-data.ttl")
    shapes, n_shapes = ntriples(HERE / "smoke-shapes.ttl")

    update = (
        f"# Generated by build_load_update.py: {n_schema} schema, {n_data} data, "
        f"{n_shapes} shape triples.\n"
        f"INSERT DATA {{\n"
        f"GRAPH <{SCHEMA_GRAPH}> {{\n{schema}\n}}\n"
        f"{data}\n"
        f"GRAPH <{SHAPES_GRAPH}> {{\n{shapes}\n}}\n"
        f"}}\n"
    )
    out = HERE / "load-all.rq"
    out.write_text(update, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {n_schema} schema + {n_data} data + {n_shapes} shape triples")


if __name__ == "__main__":
    main()
