def git_commit():
    """HEAD's commit, with "-dirty" when tracked files have uncommitted changes (the commit alone would
    then not describe the code that built the graphs); None outside a git checkout."""
    def git(*args):
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    try:
        commit = git("rev-parse", "HEAD")
        return commit + "-dirty" if git("status", "--porcelain", "--untracked-files=no") else commit
    except Exception:
        return None


def content_hash(files):
    """(sha256 of the graph as sorted canonical N-Triples, triple count): the hash is stable across
    rebuilds that change nothing, whatever the serialization order or blank node names."""
    g = Graph()
    for f in files:
        g.parse(ROOT / f)
    n = len(g)
    if any(isinstance(t, BNode) for triple in g for t in triple):
        g = to_canonical_graph(g)
    lines = sorted(g.serialize(format="nt").splitlines())
    return "sha256:" + hashlib.sha256("\n".join(l for l in lines if l).encode()).hexdigest(), n


def file_hash(path):
    return "sha256:" + hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def source_files(key):
    """The cached raw files of a source snapshot, as sorted paths relative to data/raw/."""
    return sorted({str(Path(f).relative_to(RAW)) for p in SOURCES[key][2] for f in glob.glob(str(RAW / p))
                   if Path(f).is_file()})


def source_hash(key):
    """(sha256 over the sorted (path, file sha256) list of the source's cached raw files, file count).
    Depends only on file names and contents, not on modification times, so it is stable across reruns."""
    files = source_files(key)
    if not files:
        return None, 0
    h = hashlib.sha256()
    for f in files:
        h.update(f"{f}\t{hashlib.sha256((RAW / f).read_bytes()).hexdigest()}\n".encode())
    return "sha256:" + h.hexdigest(), len(files)


def stamp(ts):
    return Literal(datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="seconds"), datatype=XSD.dateTime)


def build(manifest, now):
    """manifest: list of (file, graph IRI) as loaded; now: build time (ISO string)."""
    g = Graph()
    for prefix, ns in [("prov", PROV), ("dcterms", DCTERMS), ("d", D), ("graph", GRAPH)]:
        g.bind(prefix, ns)
    build_act = D[f"activity/build/{now}"]
    g.add((build_act, RDF.type, PROV.Activity))
    g.add((build_act, RDFS.label, Literal("pipeline build (resolve_*.py, build_skos.py, build_rdf.py)", lang="en")))
    g.add((build_act, PROV.endedAtTime, Literal(now, datatype=XSD.dateTime)))
    g.add((build_act, PROV.wasAssociatedWith, AUTHOR))
    if commit := git_commit():
        g.add((build_act, DCTERMS.hasVersion, Literal(commit)))

    used_sources = {s for _, sources, _ in LINEAGE.values() for s in sources} | \
                   {s for _, sources, _, _ in DERIVED.values() for s in sources}
    for key in sorted(used_sources):
        label, api, patterns, release = SOURCES[key]
        snap = D[f"source/{key}"]
        g.add((snap, RDF.type, PROV.Entity))
        g.add((snap, RDFS.label, Literal(label, lang="en")))
        g.add((snap, PROV.specializationOf, URIRef(api)))
        if release and (v := release()):
            g.add((snap, DCTERMS.hasVersion, Literal(v)))
        digest, n = source_hash(key)
        if digest:
            g.add((snap, DCTERMS.identifier, Literal(digest)))
            g.add((snap, DCTERMS.extent, Literal(f"{n} cached files in data/raw/")))
        times = [Path(f).stat().st_mtime for p in patterns for f in glob.glob(str(RAW / p))]
        if times:
            act = D[f"activity/retrieve/{key}"]
            g.add((act, RDF.type, PROV.Activity))
            g.add((act, RDFS.label, Literal(f"retrieval of {label} (times of the cached responses)", lang="en")))
            g.add((act, PROV.used, URIRef(api)))
            g.add((act, PROV.startedAtTime, stamp(min(times))))
            g.add((act, PROV.endedAtTime, stamp(max(times))))
            g.add((snap, PROV.wasGeneratedBy, act))

    files_by_graph = {}
    for file, iri in manifest:
        files_by_graph.setdefault(iri, []).append(file)
    for iri, files in files_by_graph.items():
        name = "schema" if iri == "tag:stardog:api:context:schema" else iri.replace(str(GRAPH), "")
        if name == "provenance":
            continue  # a graph does not describe its own hash
        step, sources, curated = LINEAGE[name]
        node = URIRef(iri)
        g.add((node, RDF.type, PROV.Entity))
        g.add((node, RDFS.label, Literal(f"graph {name}")))
        digest, n = content_hash(files)
        g.add((node, DCTERMS.identifier, Literal(digest)))
        g.add((node, DCTERMS.extent, Literal(f"{n} triples")))
        g.add((node, DCTERMS.source, Literal(", ".join(files))))
        if step == "hand-authored":
            g.add((node, PROV.wasAttributedTo, AUTHOR))
        else:
            g.add((node, PROV.wasGeneratedBy, build_act))
            g.add((node, RDFS.comment, Literal(f"generated by {step}", lang="en")))
        g.add((node, PROV.generatedAtTime, stamp(max((ROOT / f).stat().st_mtime for f in files))))
        if name == "schema":
            version = Graph().parse(ROOT / files[0]).value(URIRef(BASE + "ontology"), OWL.versionInfo)
            g.add((node, DCTERMS.hasVersion, Literal(str(version))))
        for s in sources:
            g.add((node, PROV.wasDerivedFrom, D[f"source/{s}"]))
        for c in curated:
            g.add((node, PROV.wasDerivedFrom, curated_entity(g, c)))
        for f in GENERATED.get(name, []):
            g.add((node, PROV.wasDerivedFrom, D[f"generated/{f}"]))
        if name in DESCRIPTIONS:
            g.add((node, DCTERMS.description, Literal(DESCRIPTIONS[name], lang="en")))
    add_intermediates(g)
    return g


def curated_entity(g, path):
    cur = D[f"curated/{path}"]
    g.add((cur, RDF.type, PROV.Entity))
    g.add((cur, RDFS.label, Literal(path)))
    g.add((cur, DCTERMS.identifier, Literal(file_hash(path))))
    g.add((cur, PROV.wasAttributedTo, AUTHOR))
    return cur


def add_intermediates(g):
    """Each generated intermediate: its hash, the files and sources it was derived from, and the run of the
    script that wrote it (one activity per script, timed by the last write of its outputs)."""
    needed = {f for files in GENERATED.values() for f in files} | \
             {f for _, _, _, upstream in DERIVED.values() for f in upstream}
    if missing := sorted(needed - DERIVED.keys()):
        raise SystemExit(f"provenance.DERIVED has no entry for {missing}")
    outputs = {}
    for f, (script, _, _, _) in DERIVED.items():
        outputs.setdefault(script, []).append(f)
    runs = {}
    for script, files in outputs.items():
        ended = stamp(max((ROOT / f).stat().st_mtime for f in files))
        act = D[f"activity/{Path(script).stem}/{ended}"]
        g.add((act, RDF.type, PROV.Activity))
        g.add((act, RDFS.label, Literal(script)))
        g.add((act, RDFS.comment, Literal("one run of the script; its end time is the last write of its outputs",
                                          lang="en")))
        g.add((act, PROV.endedAtTime, ended))
        g.add((act, PROV.wasAssociatedWith, AUTHOR))
        runs[script] = act
    for f, (script, sources, curated, upstream) in DERIVED.items():
        gen = D[f"generated/{f}"]
        g.add((gen, RDF.type, PROV.Entity))
        g.add((gen, RDFS.label, Literal(f)))
        g.add((gen, DCTERMS.identifier, Literal(file_hash(f))))
        g.add((gen, PROV.generatedAtTime, stamp((ROOT / f).stat().st_mtime)))
        g.add((gen, PROV.wasGeneratedBy, runs[script]))
        inputs = [D[f"source/{s}"] for s in sources] + [curated_entity(g, c) for c in curated] + \
                 [D[f"generated/{u}"] for u in upstream]
        for i in inputs:
            g.add((gen, PROV.wasDerivedFrom, i))
            g.add((runs[script], PROV.used, i))


def graph_hashes(path=ROOT / "data" / "rdf" / "provenance.ttl"):
    """{named graph IRI: content hash} as recorded by the RDF build."""
    g = Graph().parse(path)
    return {str(s): str(o) for s, o in g.subject_objects(DCTERMS.identifier) if str(s).startswith(str(GRAPH))
            or str(s) == "tag:stardog:api:context:schema"}


def build_gold(manifest):
    """PROV-O for the gold layer: one prov:Entity per Snowflake table of an export manifest (tables.json),
    derived from the named graphs it was exported from and generated by the export. Kept out of
    data/rdf/provenance.ttl: the export records that file's digest, so describing the export inside it
    would make each depend on the other."""
    g = Graph()
    for prefix, ns in [("prov", PROV), ("dcterms", DCTERMS), ("d", D), ("graph", GRAPH)]:
        g.bind(prefix, ns)
    at = manifest["exported_at"]
    act = D[f"activity/export_snowflake/{at}"]
    g.add((act, RDF.type, PROV.Activity))
    g.add((act, RDFS.label, Literal("scripts/export_snowflake.py")))
    g.add((act, PROV.endedAtTime, Literal(at, datatype=XSD.dateTime)))
    g.add((act, PROV.wasAssociatedWith, AUTHOR))
    build = D[f"rdf-build/{manifest['rdf_provenance'].removeprefix('sha256:')}"]
    g.add((build, RDF.type, PROV.Entity))
    g.add((build, RDFS.label, Literal("data/rdf/provenance.ttl of the RDF build the export read")))
    g.add((build, DCTERMS.identifier, Literal(manifest["rdf_provenance"])))
    g.add((act, PROV.used, build))
    hashes = manifest.get("graph_hashes")  # recorded by exports since 2026-11-05
    for t in manifest["tables"]:
        node = D[f"snowflake/{t['name']}"]
        g.add((node, RDF.type, PROV.Entity))
        g.add((node, RDFS.label, Literal(f"GLP.{t['name']}")))
        g.add((node, DCTERMS.identifier, Literal("sha256:" + t["sha256"])))
        g.add((node, DCTERMS.extent, Literal(f"{t['rows']} rows")))
        g.add((node, PROV.wasGeneratedBy, act))
        g.add((node, PROV.generatedAtTime, Literal(at, datatype=XSD.dateTime)))
        graphs = t.get("graphs") or re.search(r"Source: (.*)$", t["comment"])[1].split(", ")
        for iri in graphs:
            iri = iri if iri.startswith("http") else str(GRAPH[iri])
            g.add((node, PROV.wasDerivedFrom, URIRef(iri)))
            g.add((act, PROV.used, URIRef(iri)))
            if hashes and iri in hashes:
                q = BNode()
                g.add((node, PROV.qualifiedDerivation, q))
                g.add((q, RDF.type, PROV.Derivation))
                g.add((q, PROV.entity, URIRef(iri)))
                g.add((q, DCTERMS.identifier, Literal(hashes[iri])))  # the graph's content hash when exported
    if not hashes:
        g.add((act, RDFS.comment, Literal("This export predates per-graph hashes in tables.json; the graph "
                                          "versions it read are identified only by the RDF build digest.", lang="en")))
    return g


if __name__ == "__main__" and "--gold" in sys.argv:
    tables = ROOT / "data" / "snowflake" / "tables.json"
    out = ROOT / "data" / "snowflake" / "provenance.ttl"
    build_gold(json.loads(tables.read_text())).serialize(out, format="turtle")
    print(f"wrote {out.relative_to(ROOT)} from {tables.relative_to(ROOT)}")
