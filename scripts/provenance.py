"""PROV-O description of every named graph that load_stardog.py loads (used by build_rdf.py).

For each graph: what generated it and when, a content hash, the curated input files and the
generated intermediate files it depends on (each with its own hash), and the source snapshots it
was derived from. A source snapshot is one API (or download) as
retrieved for this build: prov:specializationOf the API, its release where the source publishes
one (RxNorm 05-Oct-2026, UMLS 2026AA, GLEIF golden copy, NUCC 261, ...), the retrieval
window, taken from the modification times of the cached responses in data/raw/, and a content hash
of those cached files.

The lineage is a chain, bronze -> silver -> gold, walkable with prov:wasDerivedFrom+:
  bronze  d:source/<key>         the cached API responses and downloads in data/raw/ (hashed)
  silver  d:curated/<path>       hand-curated inputs (vocab/src/*.csv, ...; hashed)
          d:generated/<path>     intermediates (data/clean/*.csv, scripts/*.csv; hashed), each derived
                                 from its own inputs and generated by the script that wrote it (DERIVED)
          graph/<name>           the named graphs (hashed as canonical N-Triples)
  gold    d:snowflake/<table>    the Snowflake tables, in a separate file written by export_snowflake.py
                                 (build_gold; see docs/decisions.md 2026-11-05 for why it is separate)
Each named graph also keeps direct prov:wasDerivedFrom links to its primary sources (one-hop summary).

Usage (gold only, from an existing export): .venv/bin/python scripts/provenance.py --gold
"""
